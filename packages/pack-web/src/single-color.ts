/** `web:color`: six shades of one color, placed like web:palette's – shade distances after Reasonable Colors by Matthew Howell (https://www.reasonable.work/colors/). */
import type { Generator } from '@codejen/jen';
import { parseColor } from './color.ts';
import { fail } from './common.ts';
import { usesTailwind } from './entry.ts';
import { groupFor, shellWord, verifyShades } from './palette.ts';
import { INTO_PARAMS, singleActions } from './single.ts';
import type { Item } from './single.ts';

export function colorItem(name: string, color: string, tailwind: boolean): Item {
  if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) fail(`web:color --name: "${name}" – use lowercase letters, digits and dashes, like pink or brand-blue`);
  const group = groupFor(name, parseColor(color, '--color'));
  verifyShades([group], 'web:color');
  const shades = group.shades.map((hex, i) => `--color-${name}-${i + 1}: ${hex};`);
  const command = `jen web:color --name=${name} --color=${shellWord(color)}${tailwind ? ' --tailwind' : ''}`;
  const header = `/*
 * Generated by \`${command}\` – re-run with --force to change it.
 * Shade distances after Reasonable Colors by Matthew Howell, https://www.reasonable.work/colors/
 */`;
  const block = (selector: string, indent: string) => `${indent}${selector} {\n${shades.map((s) => `${indent}  ${s}`).join('\n')}\n${indent}}`;
  const rules = `${header}\n${block(tailwind ? '@theme' : ':root', '')}`;
  const css = tailwind ? `${rules}\n` : `${header}\n@layer tokens {\n${block(':root', '  ')}\n}\n`;
  return { path: `colors/${name}.css`, css, rules, defines: `--color-${name}-1` };
}

const colorGenerator: Generator = {
  description: 'create six shades of one color, lightest to darkest (--color-<name>-1 … -6), without light/dark roles – for an accent color, web:palette --secondary checks its pairs',
  params: {
    name: { description: 'what to call it: pink makes --color-pink-1 … --color-pink-6' },
    color: { description: 'the color: any CSS color (deeppink, #f37, rgb(), hsl(), oklch() …) or a hue in degrees' },
    ...INTO_PARAMS,
    tailwind: { default: false, description: 'write Tailwind\'s @theme instead, for bg-pink-1 and friends – on by itself in a Tailwind project' },
  },
  examples: ['--name=pink --color=deeppink', '--name=brand --color=#5b5bd6 --dir=src/css', '--name=pink --color=deeppink --into=css/tokens.css'],
  actions: ({ name, color, into, tailwind }, _helpers, ctx) =>
    singleActions(ctx, colorItem(String(name), String(color), Boolean(tailwind) || usesTailwind(ctx)), into),
};

export default colorGenerator;
